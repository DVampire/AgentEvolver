(() => {
  const tabs = [...document.querySelectorAll('[data-example]')];
  function activate(tab) {
    tabs.forEach(button => {
      const active = button === tab;
      button.setAttribute('aria-selected', String(active));
      button.tabIndex = active ? 0 : -1;
      document.getElementById(button.getAttribute('aria-controls')).hidden = !active;
    });
    document.querySelector('.copy-status').textContent = '';
  }
  tabs.forEach((tab, i) => {
    tab.addEventListener('click', () => activate(tab));
    tab.addEventListener('keydown', event => {
      let next;
      if (event.key === 'ArrowRight') next = tabs[(i + 1) % tabs.length];
      if (event.key === 'ArrowLeft') next = tabs[(i + tabs.length - 1) % tabs.length];
      if (event.key === 'Home') next = tabs[0];
      if (event.key === 'End') next = tabs[tabs.length - 1];
      if (next) { event.preventDefault(); activate(next); next.focus(); }
    });
  });
  document.querySelector('.copy-command').addEventListener('click', async () => {
    const code = document.querySelector('[role="tabpanel"]:not([hidden]) code');
    const status = document.querySelector('.copy-status');
    const zh = document.documentElement.lang.startsWith('zh');
    try {
      await navigator.clipboard.writeText(code.textContent);
      status.textContent = zh ? '命令已复制。' : 'Command copied.';
    } catch {
      const range = document.createRange(); range.selectNodeContents(code);
      const selection = window.getSelection(); selection.removeAllRanges(); selection.addRange(range);
      status.textContent = zh ? '已选中命令，请手动复制。' : 'Command selected. Copy it with your keyboard.';
    }
  });
})();
